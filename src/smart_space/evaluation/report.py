"""Render ``docs/results.md`` from ``runs/eval/metrics.json`` so the committed
results table is always reproducible, never hand-typed.

    python -m smart_space.evaluation.report
"""

from __future__ import annotations

import json
from datetime import date

from smart_space.config import DOCS_DIR, EVAL_DIR

MODEL_LABELS = {
    "yolo": "YOLOv8n (detection)",
    "resnet": "ResNet18 (regressor)",
    "xgboost": "XGBoost + ResNet feats",
    "density": "CSRNet-lite (density)",
}


def render() -> str:
    metrics = json.loads((EVAL_DIR / "metrics.json").read_text())
    n = next(iter(metrics.values()))["n"]

    lines = [
        "# Results",
        "",
        f"_Generated by `smartspace evaluate` + `python -m smart_space.evaluation.report` "
        f"on {date.today().isoformat()}. Test set: {n} images._",
        "",
        "## Headline (test set, lower is better except exact-match)",
        "",
        "| Model | MAE | MAE 95% CI | RMSE | MAPE % | Exact % | Bias |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    ranked = sorted(metrics.items(), key=lambda kv: kv[1]["overall"]["mae"]["value"])
    for name, res in ranked:
        o = res["overall"]
        lines.append(
            f"| {MODEL_LABELS.get(name, name)} "
            f"| {o['mae']['value']:.3f} "
            f"| [{o['mae']['ci_low']:.2f}, {o['mae']['ci_high']:.2f}] "
            f"| {o['rmse']['value']:.3f} "
            f"| {o['mape']['value']:.1f} "
            f"| {o['exact_match_pct']['value']:.1f} "
            f"| {res['mean_bias']:+.2f} |"
        )

    best = ranked[0][0]
    lines += ["", f"**Best by MAE: {MODEL_LABELS.get(best, best)}.**", "", "## Error by density bucket (MAE)", ""]
    buckets = ["empty", "low", "medium", "high"]
    lines.append("| Model | " + " | ".join(buckets) + " |")
    lines.append("| --- |" + " --- |" * len(buckets))
    for name, res in ranked:
        cells = []
        for b in buckets:
            pb = res["per_bucket"].get(b)
            cells.append(f"{pb['mae']:.2f} (n={pb['n']})" if pb else "—")
        lines.append(f"| {MODEL_LABELS.get(name, name)} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Figures",
        "",
        "See `runs/eval/figures/`: `pred_vs_true.png`, `error_by_bucket.png`, "
        "`calibration.png`, `roc_occupied.png`.",
        "",
        "## Caveat",
        "",
        "Absolute numbers are **optimistic** — the Roboflow export contains 2 augmented "
        "copies per source image and the split is stratified by count but not grouped by "
        "source id. See [`data_card.md`](data_card.md).",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out = DOCS_DIR / "results.md"
    out.write_text(render())
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
